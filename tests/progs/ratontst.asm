; RATONTST.COM - prueba del análisis del descriptor de informe de los ratones
; y paneles USB (lib/hidraton.inc) y de la lectura de sus informes
; (lib/hidratx.inc), el mismo código que lleva HSPUSB.SYS: descriptores de
; ratones de distintas clases y un informe de ejemplo de cada uno. Escribe el
; mapa y lo que lee; tests/run_usbauto_tests.sh lo compara.
        cpu 386
        bits 16
        org 0x100

        mov si, casos
.c:
        mov bx, [si]
        test bx, bx
        jz .fin
        push si
        mov si, bx
        call puts
        pop si
        push si
        mov cx, [si+4]
        mov si, [si+2]
        call hr_parse
        pop si
        jnc .ok
        push si
        mov si, m_no
        call puts
        pop si
        jmp .sig
.ok:
        push si
        mov si, m_id
        call puts
        movzx eax, byte [hr_rid]
        cmp byte [hr_hasid], 0
        jne .i
        mov eax, -1
.i:
        call putsig
        mov si, m_x
        call puts
        movzx eax, word [hr_xo]
        call putnum
        mov al, '/'
        call putc
        movzx eax, byte [hr_xs]
        call putnum
        mov si, m_y
        call puts
        movzx eax, word [hr_yo]
        call putnum
        mov al, '/'
        call putc
        movzx eax, byte [hr_ys]
        call putnum
        mov si, m_b
        call puts
        movsx eax, word [hr_b1]
        call putsig
        mov al, ','
        call putc
        movsx eax, word [hr_b2]
        call putsig
        mov al, ','
        call putc
        movsx eax, word [hr_b3]
        call putsig
        call crlf
        pop si
        ; los informes de ejemplo (DW: puntero, bytes; 0 = fin)
        mov di, [si+6]
.r:
        mov bx, [di]
        test bx, bx
        jz .sig
        push si
        push di
        mov cx, [di+2]
        mov si, bx
        mov di, bufer
        cld
        rep movsb
        mov si, bufer
        call hr_extract
        jnc .ex
        mov si, m_otro
        call puts
        jmp .rn
.ex:
        push dx
        push cx
        mov si, m_lee
        call puts
        movzx eax, bx
        call putnum
        mov si, m_dx
        call puts
        pop ax
        movsx eax, ax
        call putsig
        mov si, m_dy
        call puts
        pop ax
        movsx eax, ax
        call putsig
        call crlf
.rn:
        pop di
        pop si
        add di, 4
        jmp .r
.sig:
        add si, 8
        jmp .c
.fin:
        mov ax, 0x4C00
        int 0x21

; EAX con signo
putsig:
        test eax, eax
        jns .p
        push ax
        mov al, '-'
        call putc
        pop ax
        neg eax
.p:
        call putnum
        ret

