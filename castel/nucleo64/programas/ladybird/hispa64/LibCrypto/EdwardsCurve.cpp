ErrorOr<bool> ed25519_verify(ReadonlyBytes public_key, ReadonlyBytes signature, ReadonlyBytes message)
{
    if (es_de_orden_pequeño(public_key))
        return false;
    if (signature.size() >= 32 && es_de_orden_pequeño(signature.slice(0, 32)))
        return false;
    // (OpenSSL no acepta una clave que no sea de 32 octetos: es un error, no «no vale»)
    if (public_key.size() != 32)
        return Error::from_string_literal("EVP_PKEY_new_raw_public_key_ex failed");
    if (signature.size() != 64)
        return false;
    return crypto_ed25519_check(signature.data(), public_key.data(), message.data(), message.size()) == 0;
}

